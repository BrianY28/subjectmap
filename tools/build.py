#!/usr/bin/env python3
"""Validate all subjects and build their indexes, OPML files and shared site.

Python 3.9+, standard library only. Adapted from Physics Map (MIT).
Run with --check to verify tracked generated files without writing them.
"""
import argparse
import datetime
import html
import json
import re
import shutil
import sys
from pathlib import Path
from urllib.parse import urlsplit
from xml.sax.saxutils import quoteattr

sys.path.insert(0, str(Path(__file__).resolve().parent))
import nodelib

ROOT = nodelib.ROOT
TEMPLATES = Path(__file__).resolve().parent
MARKMAP = "https://cdn.jsdelivr.net/npm/markmap-autoloader@0.18.12"
STALE_DAYS = 365
GENERATED = "<!-- Generated by tools/build.py from subjects/. Edit the source files, not this file. -->"
SLUG = re.compile(r"[a-z0-9]+(?:-[a-z0-9]+)*")


def esc(value):
    return html.escape(str(value), quote=True)


def md_text(value):
    """Literal text in a Markdown label or table, with no raw HTML."""
    return re.sub(r"([\\`*_{\[\]()#+.!|}-])", r"\\\1", html.escape(str(value), quote=False)).replace("\n", " ")


def load_config(root=None):
    root = Path(root) if root is not None else ROOT
    config = json.loads((root / "subjects.json").read_text(encoding="utf-8"))
    if not isinstance(config, dict):
        raise nodelib.NodeError("subjects.json: expected an object")
    for key in ("title", "repository", "site_url"):
        if not isinstance(config.get(key), str) or not config[key].strip():
            raise nodelib.NodeError(f"subjects.json: '{key}' must be a nonempty string")
    for key in ("repository", "site_url"):
        try:
            url = urlsplit(config[key])
        except ValueError as error:
            raise nodelib.NodeError(f"subjects.json: '{key}' is not a valid HTTPS URL") from error
        if (url.scheme != "https" or not url.netloc or url.username or url.password
                or url.query or url.fragment or any(c.isspace() for c in config[key])):
            raise nodelib.NodeError(f"subjects.json: '{key}' must be an HTTPS base URL without credentials, query or fragment")
    subjects = config.get("subjects")
    if not isinstance(subjects, list) or not subjects:
        raise nodelib.NodeError("subjects.json: add at least one subject")
    seen = set()
    fields = ("id", "name", "title", "map_title", "headline", "description", "symbol", "explainer")
    for subject in subjects:
        if not isinstance(subject, dict):
            raise nodelib.NodeError("subjects.json: each subject must be an object")
        for key in fields:
            if not isinstance(subject.get(key), str) or not subject[key].strip():
                raise nodelib.NodeError(f"subjects.json: subject '{key}' must be a nonempty string")
        slug = subject["id"]
        if not SLUG.fullmatch(slug) or slug == "assets":
            raise nodelib.NodeError("subjects.json: subject id must be lowercase-words and cannot be 'assets'")
        if slug in seen:
            raise nodelib.NodeError(f"subjects.json: duplicate subject id '{slug}'")
        seen.add(slug)
        if not SLUG.fullmatch(subject["explainer"]):
            raise nodelib.NodeError(f"subjects.json: {slug} explainer must be lowercase-words")
        subject_root = root / "subjects" / slug
        if not subject_root.is_dir() or not subject_root.resolve().is_relative_to((root / "subjects").resolve()):
            raise nodelib.NodeError(f"subjects/{slug}/: missing directory or path outside subjects/")
        explainer = subject_root / "explainers" / subject["explainer"] / "index.html"
        if not explainer.is_file() or not explainer.resolve().is_relative_to(subject_root.resolve()):
            raise nodelib.NodeError(f"subjects/{slug}/: configured explainer must be an existing page inside the subject")
    return config


def load_subjects(config, root=None):
    root = Path(root) if root is not None else ROOT
    subjects = []
    for metadata in config["subjects"]:
        subject_root = root / "subjects" / metadata["id"]
        try:
            branches = nodelib.load(subject_root)
            errors = nodelib.validate(branches, subject_root)
            if errors:
                raise nodelib.NodeError("\n".join(errors))
        except nodelib.NodeError as error:
            raise nodelib.NodeError(f"subjects/{metadata['id']}/: {error}") from error
        subjects.append({**metadata, "root": subject_root, "branches": branches})
    return subjects


def warnings(branches, today):
    out = []
    for branch in branches:
        for node in branch["nodes"]:
            if node["status"] == "open":
                age = (today - datetime.date.fromisoformat(node["as_of"])).days
                if age > STALE_DAYS:
                    out.append(f"{node['path']}: open topic last checked {age} days ago; please re-check it")
                elif age < 0:
                    out.append(f"{node['path']}: review date {node['as_of']} is in the future")
    return out


def explainer_name(concept):
    return Path(concept["explainer"]).name


def explainer_url(subject, concept, config):
    return f"{config['site_url'].rstrip('/')}/{subject['id']}/explainers/{explainer_name(concept)}/"


def counts(branches):
    nodes = [node for branch in branches for node in branch["nodes"]]
    return len(nodes), sum(len(node["concepts"]) for node in nodes)


def subject_index(subject):
    branches = subject["branches"]
    total, concepts = counts(branches)
    reviewed = sum(any("(AI)" not in name for name in node.get("reviewed_by", []))
                   for branch in branches for node in branch["nodes"])
    lines = [GENERATED, "", f"# {md_text(subject['title'])} index", "",
             f"{len(branches)} branches, {total} topics, {concepts} concepts. "
             f"{reviewed} of {total} topics have a recorded human review.", "",
             "[All subjects](../../INDEX.md) · [Subject guide](README.md) · [Download OPML](map.opml)", ""]
    for branch in branches:
        lines += [f"## [{md_text(branch['title'])}]({branch['path']})", "",
                  f"{md_text(branch['span'])} · {md_text(branch['summary'])}", "",
                  "| Topic | Historical context | Status | Concepts | Sources | Reviewed by |",
                  "| --- | --- | --- | --- | --- | --- |"]
        for node in branch["nodes"]:
            status = "open, as of " + node["as_of"] if node["status"] == "open" else "established"
            names = []
            for concept in node["concepts"]:
                label = md_text(concept["title"])
                if "explainer" in concept:
                    label += f" ([explainer](explainers/{explainer_name(concept)}/index.html))"
                names.append(label)
            reviewers = ", ".join(node.get("reviewed_by", [])) or "Awaiting review"
            lines.append(f"| [{md_text(node['title'])}]({node['path']}) | {md_text(node['when'])} | {status} | "
                         f"{'; '.join(names)} | {len(node['sources'])} | {md_text(reviewers)} |")
        lines.append("")
    return "\n".join(lines).rstrip() + "\n"


def root_index(config, subjects):
    total = sum(counts(s["branches"])[0] for s in subjects)
    concepts = sum(counts(s["branches"])[1] for s in subjects)
    lines = [GENERATED, "", f"# {md_text(config['title'])} index", "",
             f"{len(subjects)} subjects, {total} topics, {concepts} concepts.", "",
             "Choose a subject to browse its branches, concepts and sources. "
             "Build the interactive site with `python3 tools/build.py`; see [README.md](README.md).", "",
             "| Subject | Branches | Topics | Concepts | Export |",
             "| --- | ---: | ---: | ---: | --- |"]
    for subject in subjects:
        nodes, concepts = counts(subject["branches"])
        path = "subjects/" + subject["id"]
        lines.append(f"| [{md_text(subject['name'])}]({path}/INDEX.md) | {len(subject['branches'])} | {nodes} | {concepts} | [OPML]({path}/map.opml) |")
    return "\n".join(lines) + "\n"


def opml(subject, config):
    title = subject["map_title"]
    lines = ['<?xml version="1.0" encoding="UTF-8"?>', '<opml version="2.0">',
             f"  <head><title>{esc(title)}</title></head>", "  <body>",
             f"    <outline text={quoteattr(title)} _note={quoteattr('Open source: ' + config['repository'])}>"]
    for branch in subject["branches"]:
        lines.append(f"      <outline text={quoteattr(branch['title'])} _note={quoteattr(branch['span'] + ' · ' + branch['summary'])}>")
        for node in branch["nodes"]:
            meta = node["when"] + (" · " + ", ".join(node["people"]) if node.get("people") else "")
            if node["status"] == "open":
                meta += f" · open question, as of {node['as_of']}"
            note = meta + "\n" + node["note"] + "\nSources:\n" + "\n".join("- " + source for source in node["sources"])
            lines.append(f"        <outline text={quoteattr(node['title'])} _note={quoteattr(note)}>")
            for concept in node["concepts"]:
                note = concept["note"]
                if "explainer" in concept:
                    note += "\nExplainer (after publication): " + explainer_url(subject, concept, config)
                lines.append(f"          <outline text={quoteattr(concept['title'])} _note={quoteattr(note)}/>")
            lines.append("        </outline>")
        lines.append("      </outline>")
    lines += ["    </outline>", "  </body>", "</opml>"]
    return "\n".join(lines) + "\n"


def markmap_md(subject):
    lines = ["---", "markmap:", "  initialExpandLevel: 2", "  colorFreezeLevel: 2", "  maxWidth: 280", "---",
             "# " + md_text(subject["map_title"])]
    for branch in subject["branches"]:
        lines.append(f"## [{md_text(branch['title'])}](#branch-{branch['dir']})")
        for node in branch["nodes"]:
            tag = " <small>open</small>" if node["status"] == "open" else ""
            lines.append(f"### [{md_text(node['title'])}](nodes/{node['id']}.html){tag}")
            for concept in node["concepts"]:
                link = f" · [explainer](explainers/{explainer_name(concept)}/)" if "explainer" in concept else ""
                lines.append("- " + md_text(concept["title"]) + link)
    return "\n".join(lines)


def source_html(source):
    """Link only HTTP(S) URLs, and escape all other citation text."""
    parts, end = [], 0
    for match in re.finditer(r'https?://[^\s<>"\']+', source):
        url = match.group().rstrip(".,;")
        parts += [esc(source[end:match.start()]), f'<a href="{esc(url)}">{esc(url)}</a>']
        end = match.start() + len(url)
    parts.append(esc(source[end:]))
    return "".join(parts)


def branch_html(branch):
    topics = []
    for node in branch["nodes"]:
        search = " ".join([branch["title"], node["title"], node["note"], *node.get("people", []),
                           *[c["title"] + " " + c["note"] for c in node["concepts"]]])
        tag = '<span class="open-tag">Open</span>' if node["status"] == "open" else ""
        topics.append(f'<li data-search="{esc(search)}"><a href="nodes/{node["id"]}.html">{esc(node["title"])}{tag}</a></li>')
    return (f'<section class="branch" id="branch-{branch["dir"]}"><div class="branch-meta">'
            f'<span>Branch {branch["dir"][:2]}</span><span>{esc(branch["span"])}</span></div>'
            f'<h3>{esc(branch["title"])}</h3><p class="branch-summary">{esc(branch["summary"])}</p>'
            f'<ul class="topic-list">{"".join(topics)}</ul></section>')


def stats_html(subject):
    total, concepts = counts(subject["branches"])
    return f'<span><strong>{len(subject["branches"])}</strong> branches</span><span><strong>{total}</strong> topics</span><span><strong>{concepts}</strong> concepts</span>'


def subject_nav(subjects, active, prefix="../"):
    links = []
    for subject in subjects:
        current = ' aria-current="page"' if subject["id"] == active else ''
        links.append(f'<a href="{prefix}{subject["id"]}/"{current}>{esc(subject["name"])}</a>')
    return "".join(links)


def subject_card(subject):
    slug = subject["id"]
    return (f'<article class="subject-card" data-subject="{slug}">'
            f'<div class="subject-card-top"><span class="subject-symbol" aria-hidden="true">{esc(subject["symbol"])}</span>'
            f'<span class="eyebrow">{esc(subject["name"])} map</span></div>'
            f'<h2><a href="{slug}/index.html">{esc(subject["name"])}</a></h2>'
            f'<p class="subject-description">{esc(subject["description"])}</p>'
            f'<div class="stats subject-stats">{stats_html(subject)}</div><div class="subject-actions">'
            f'<a class="button-link" href="{slug}/index.html">Explore {esc(subject["name"])} <span aria-hidden="true">→</span></a>'
            f'<a href="{slug}/map.opml" download>Download OPML</a></div>'
            f'<a class="subject-explainer" href="{slug}/explainers/{subject["explainer"]}/">Try an interactive explainer →</a></article>')


def topic_page(subject, branch, node, config, subjects):
    concepts = []
    for concept in node["concepts"]:
        link = (f'<a class="explainer-link" href="../explainers/{explainer_name(concept)}/">Explore this concept interactively →</a>'
                if "explainer" in concept else "")
        concepts.append(f'<li><strong>{esc(concept["title"])}</strong>: {esc(concept["note"])}{link}</li>')
    status = "Open research question · checked " + node["as_of"] if node["status"] == "open" else "Established topic"
    reviewers = ", ".join(node.get("reviewed_by", [])) or "Awaiting review; no subject review is recorded."
    people = f'<span>{esc(", ".join(node["people"]))}</span>' if node.get("people") else ""
    sources = "".join("<li>" + source_html(source) + "</li>" for source in node["sources"])
    source = config["repository"].rstrip('/') + '/blob/main/subjects/' + subject["id"] + '/' + node["path"]
    return f'''<!doctype html>
<html lang="en"><head><meta charset="utf-8"><meta name="viewport" content="width=device-width, initial-scale=1">
<meta name="description" content="{esc(node['note'])}"><title>{esc(node['title'])} — {esc(subject['title'])}</title>
<link rel="stylesheet" href="../../assets/site.css"></head><body data-subject="{subject['id']}">
<a href="#topic" class="skip">Skip to topic</a>
<header class="topbar"><a class="brand" href="../index.html"><span class="brand-mark" aria-hidden="true">{esc(subject['symbol'])}</span>{esc(subject['title'])}</a>
<nav aria-label="Main navigation"><a href="../../index.html">All subjects</a>{subject_nav(subjects, subject['id'], '../../')}<a href="../map.opml" download>Download OPML</a></nav></header>
<main class="article" id="topic"><div class="breadcrumbs"><a href="../index.html#branch-{branch['dir']}">{esc(branch['title'])}</a></div>
<div class="eyebrow">{esc(status)}</div><h1>{esc(node['title'])}</h1>
<div class="article-meta"><span>Historical context: {esc(node['when'])}</span>{people}</div>
<p class="lead">{esc(node['note'])}</p><h2>Key concepts</h2><ul class="concepts">{''.join(concepts)}</ul>
<h2>Sources</h2><ol class="sources">{sources}</ol>
<aside class="review" aria-label="Review status"><p><strong>Drafted by:</strong> {esc(node.get('drafted_by', 'Not recorded'))}</p>
<p><strong>Reviewed by:</strong> {esc(reviewers)}</p><p>Help improve this topic by checking a claim against its source.</p></aside>
<p class="source-link"><a href="{esc(source)}">View or edit the source on GitHub</a> · Available after repository publication</p>
<footer class="footer"><span>{esc(config['title'])} · Content CC BY-SA 4.0</span><a href="../index.html">Back to the map</a></footer></main></body></html>
'''


def render_template(name, values):
    """Single-pass substitution never expands tokens inside source data."""
    template = (TEMPLATES / name).read_text(encoding="utf-8")
    try:
        return re.sub(r"__([A-Z_]+)__", lambda m: values[m.group(1)], template)
    except KeyError as error:
        raise nodelib.NodeError(f"{name}: unknown template token {error.args[0]}") from error


def build_site(config, subjects, outputs):
    site = ROOT / "site"
    if site.exists():
        shutil.rmtree(site)
    (site / "assets").mkdir(parents=True)
    (site / ".nojekyll").write_text("", encoding="utf-8")
    for name in ("site.css", "site.js"):
        shutil.copyfile(TEMPLATES / name, site / "assets" / name)
    total = sum(counts(s["branches"])[0] for s in subjects)
    concepts = sum(counts(s["branches"])[1] for s in subjects)
    hub = render_template("hub.html", {
        "SITE_TITLE": esc(config["title"]), "REPO": esc(config["repository"].rstrip('/')),
        "STATS": f'<span><strong>{len(subjects)}</strong> subjects</span><span><strong>{total}</strong> topics</span><span><strong>{concepts}</strong> concepts</span>',
        "SUBJECTS": "\n".join(subject_card(subject) for subject in subjects),
    })
    (site / "index.html").write_text(hub, encoding="utf-8")
    for subject in subjects:
        branches = subject["branches"]
        dest_root = site / subject["id"]
        (dest_root / "nodes").mkdir(parents=True)
        values = {"SITE_TITLE": esc(config["title"]), "SUBJECT_ID": subject["id"],
                  "SUBJECT_NAME": esc(subject["name"]), "SUBJECT_TITLE": esc(subject["title"]),
                  "MAP_TITLE": esc(subject["map_title"]), "HEADLINE": esc(subject["headline"]),
                  "DESCRIPTION": esc(subject["description"]), "SYMBOL": esc(subject["symbol"]),
                  "EXPLAINER": subject["explainer"], "SUBJECT_NAV": subject_nav(subjects, subject["id"]),
                  "STATS": stats_html(subject), "BRANCH_COUNT": str(len(branches)), "NODE_COUNT": str(counts(branches)[0]),
                  "BRANCHES": "\n".join(branch_html(branch) for branch in branches),
                  "MARKDOWN": markmap_md(subject), "MARKMAP": esc(MARKMAP)}
        (dest_root / "index.html").write_text(render_template("site.html", values), encoding="utf-8")
        (dest_root / "map.opml").write_text(outputs[f"subjects/{subject['id']}/map.opml"], encoding="utf-8")
        for branch in branches:
            for node in branch["nodes"]:
                (dest_root / "nodes" / (node["id"] + ".html")).write_text(topic_page(subject, branch, node, config, subjects), encoding="utf-8")
        explainers_root = subject["root"] / "explainers"
        for fragment in sorted(explainers_root.glob("*/index.html")):
            if not fragment.resolve().is_relative_to(explainers_root.resolve()):
                raise nodelib.NodeError(f"{fragment}: explainer must stay inside its subject's explainers/")
            dest = dest_root / "explainers" / fragment.parent.name / "index.html"
            dest.parent.mkdir(parents=True, exist_ok=True)
            body = fragment.read_text(encoding="utf-8")
            title_match = re.search(r"<title\b[^>]*>(.*?)</title\s*>", body, flags=re.I | re.S)
            title = html.unescape(title_match.group(1)).strip() if title_match else fragment.parent.name.replace("-", " ").capitalize()
            body = re.sub(r"<title\b[^>]*>.*?</title\s*>", "", body, flags=re.I | re.S)
            dest.write_text('<!doctype html>\n<html lang="en"><head><meta charset="utf-8">'
                            '<meta name="viewport" content="width=device-width, initial-scale=1, viewport-fit=cover">'
                            f'<title>{esc(title)} — {esc(subject["title"])}</title></head><body>\n'
                            + body + '\n</body></html>\n', encoding="utf-8")
    return site


def generated_outputs(config, subjects):
    outputs = {"INDEX.md": root_index(config, subjects)}
    for subject in subjects:
        prefix = "subjects/" + subject["id"] + "/"
        outputs[prefix + "INDEX.md"] = subject_index(subject)
        outputs[prefix + "map.opml"] = opml(subject, config)
    return outputs


def main(argv=None):
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument("--check", action="store_true", help="validate all subjects without changing generated files")
    args = parser.parse_args(argv)
    try:
        config = load_config()
        subjects = load_subjects(config)
        for subject in subjects:
            for warning in warnings(subject["branches"], datetime.date.today()):
                print(f"warning: subjects/{subject['id']}/: {warning}")
        outputs = generated_outputs(config, subjects)
        total = sum(counts(subject["branches"])[0] for subject in subjects)
        if args.check:
            stale = [name for name, content in outputs.items()
                     if not (ROOT / name).is_file() or (ROOT / name).read_text(encoding="utf-8") != content]
            if stale:
                print(f"error: {', '.join(stale)} out of date. Run python3 tools/build.py and commit the result.")
                return 1
            print(f"ok: {len(subjects)} subjects, {total} topics; generated files are up to date")
            return 0
        for name, content in outputs.items():
            (ROOT / name).write_text(content, encoding="utf-8")
        build_site(config, subjects, outputs)
        print(f"ok: {len(subjects)} subjects, {total} topics; wrote indexes, per-subject OPML and site/")
        return 0
    except (nodelib.NodeError, OSError, UnicodeError, json.JSONDecodeError) as error:
        print(f"error: {error}")
        return 1


if __name__ == "__main__":
    sys.exit(main())
